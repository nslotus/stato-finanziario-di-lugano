// npm run docs — writes SOURCES.md and FIGURES.md from the manifest and the page's data, so the tables can never
// drift from what the page shows. npm run verify fails if either file is out of date.

import { readFileSync, writeFileSync } from "node:fs";
import { loadSite } from "./sitedata";

const manifest: any[] = JSON.parse(readFileSync("sources/MANIFEST.json", "utf8"));
const { D, X } = loadSite();
const cell = (x: unknown) => String(x ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const num = (v: number, d?: number) => v.toLocaleString("en-GB", { minimumFractionDigits: d ?? (Math.abs(v) >= 100 || Number.isInteger(v) ? 0 : 2), maximumFractionDigits: d ?? (Math.abs(v) >= 100 || Number.isInteger(v) ? 0 : 2) });

// ---- which figures cite each file
const citedBy = new Map<string, Set<string>>();
const cite = (file: string, who: string) => { if (!citedBy.has(file)) citedBy.set(file, new Set()); citedBy.get(file)!.add(who); };
for (const st of Object.values<any>(X.stars)) for (const src of st.source ?? []) cite(src.file, st.id);
for (const c of X.chapters) for (const src of c.source ?? []) cite(src.file, `chapter:${c.id}`);
for (const src of [...D.linesSource, ...D.trendSource]) cite(src.file, "the 2025 spending lines");
for (const src of D.org.source) cite(src.file, "the department view");

const kb = (b: number) => (b >= 1e6 ? `${(b / 1e6).toFixed(1)} MB` : `${Math.round(b / 1024)} KB`);
const sources = `# Sources

Every document the figures come from, archived in [\`sources/\`](sources/) exactly as downloaded. Generated by \`npm run docs\` from
[\`sources/MANIFEST.json\`](sources/MANIFEST.json); \`npm run verify\` recomputes every SHA-256 and fails if a file changed.
The documents remain under the terms of their publishers (see [\`sources/README.md\`](sources/README.md)).

${manifest.length} documents, ${kb(manifest.reduce((t, m) => t + m.bytes, 0))}.

| File | Publisher | Original | Retrieved | Size | SHA-256 | Cited by |
|---|---|---|---|---|---|---|
${manifest.map((m) => `| [\`${cell(m.file.replace("sources/", ""))}\`](${encodeURI(m.file)}) | ${cell(m.publisher)} | [link](${m.url}) | ${m.retrieved.slice(0, 10)} | ${kb(m.bytes)} | \`${m.sha256.slice(0, 16)}…\` | ${(citedBy.get(m.file)?.size ?? 0)} |`).join("\n")}
`;
writeFileSync("SOURCES.md", sources);

// ---- every figure on the page
const sectorName = (code: string) => D.fns.find((f: any) => f.code === code)?.name.en ?? code;
const loc = (src: any[]) => (src ?? []).map((x: any) => `\`${x.file.replace("sources/", "")}\`${x.locator ? `: ${cell(x.locator)}` : ""}`).join("<br>");
const rows: string[] = [];
const row = (where: string, st: any) => rows.push(`| ${cell(where)} | \`${st.id}\` | ${cell(st.label.en)} | ${num(st.value, st.digits)} | ${cell(st.unit)} | ${st.year} | ${st.kind ?? ""} | ${st.rank ? `${st.rank.rank}/${st.rank.of}` : ""} | ${loc(st.source)} |`);
for (const f of D.fns) {
  if (X.anchors[f.code]) row(`${f.code} ${f.name.en}`, X.stars[X.anchors[f.code]]);
  for (const x of f.facts) row(`${f.code} ${f.name.en}`, X.stars[x.id]);
}
row("overview", X.stars["bilancio.spesa"]);
for (const sl of D.org.slices) for (const x of sl.facts) row(`department ${sl.code}`, X.stars[x.id]);

const figures = `# Figures

Every figure the page shows besides the spending lines, with its value, unit, year and where it was read. Generated by
\`npm run docs\` from [\`docs/data/\`](docs/data/) (both data files, joined). \`kind\`: **official** = printed by the publisher; **derived** =
calculated here from official numbers (the method is on the page and in the data). Rank: Lugano among Ticino's 106
municipalities, 1 = highest value. How each number is read and checked: [\`METHOD.md\`](METHOD.md).

The ${D.lines.length} spending lines of the sky (2025 budget and actual, by function) and the ${D.org.lines.length} cost centres of the department view
come from ${[...new Set([...D.linesSource, ...D.org.source].map((x: any) => `\`${x.file.replace("sources/", "")}\``))].join(", ")}; their page references are in the data.

| Sector | Id | Figure | Value | Unit | Year | Kind | Rank | Source and location |
|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}
`;
writeFileSync("FIGURES.md", figures);
console.log(`SOURCES.md ${manifest.length} documents · FIGURES.md ${rows.length} figures`);
